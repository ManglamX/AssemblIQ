using FluentAssertions;

using Microsoft.EntityFrameworkCore;

using SmartTorque.Core.Entities;
using SmartTorque.Core.Enums;
using SmartTorque.Data;
using SmartTorque.Services;

using Xunit;

namespace SmartTorque.Tests.Services;

public class DeviceServiceTests
{
    private static AppDbContext CreateInMemoryDbContext()
    {
        var options = new DbContextOptionsBuilder<AppDbContext>()
            .UseInMemoryDatabase(Guid.NewGuid().ToString())
            .Options;
        return new AppDbContext(options);
    }

    [Fact]
    public async Task RegisterAsync_WithAutoGeneratedApiKey_CreatesDeviceAndHashedKey()
    {
        using var db = CreateInMemoryDbContext();
        var service = new DeviceService(db);

        var request = new RegisterDeviceRequest(
            TransmitterId: "TORQUE-01",
            Name: "Station 1 Torque Wrench",
            InstrumentType: InstrumentType.Torque,
            Location: "Station 1",
            FirmwareVersion: "1.0.0"
        );

        var result = await service.RegisterAsync(request, "admin");

        result.Should().NotBeNull();
        result.RawApiKey.Should().StartWith("st_");
        result.Device.TransmitterId.Should().Be("TORQUE-01");
        result.Device.ApiKeyHash.Should().Be(DeviceService.HashApiKey(result.RawApiKey));
        result.Device.IsActive.Should().BeTrue();

        var stored = await db.Devices.FirstOrDefaultAsync(d => d.TransmitterId == "TORQUE-01");
        stored.Should().NotBeNull();
        stored!.Name.Should().Be("Station 1 Torque Wrench");
    }

    [Fact]
    public async Task RegisterAsync_WithExplicitApiKey_StoresHashedKeyAndReturnsOriginal()
    {
        using var db = CreateInMemoryDbContext();
        var service = new DeviceService(db);

        const string explicitKey = "secret_key_12345";
        var request = new RegisterDeviceRequest(
            TransmitterId: "VERNIER-01",
            Name: "Station 1 Caliper",
            InstrumentType: InstrumentType.Vernier,
            ExplicitApiKey: explicitKey
        );

        var result = await service.RegisterAsync(request, "admin");

        result.RawApiKey.Should().Be(explicitKey);
        result.Device.ApiKeyHash.Should().Be(DeviceService.HashApiKey(explicitKey));
    }

    [Fact]
    public async Task RegisterAsync_DuplicateTransmitterId_ThrowsInvalidOperationException()
    {
        using var db = CreateInMemoryDbContext();
        var service = new DeviceService(db);

        var request = new RegisterDeviceRequest(
            TransmitterId: "TORQUE-DUP",
            Name: "Torque 1",
            InstrumentType: InstrumentType.Torque
        );

        await service.RegisterAsync(request, "admin");

        var act = async () => await service.RegisterAsync(request, "admin");
        await act.Should().ThrowAsync<InvalidOperationException>()
            .WithMessage("*already exists*");
    }

    [Fact]
    public async Task VerifyApiKeyAsync_ValidKey_ReturnsDeviceAndUpdatesLastSeenAt()
    {
        using var db = CreateInMemoryDbContext();
        var service = new DeviceService(db);

        const string key = "my_valid_secret_key";
        var reg = await service.RegisterAsync(
            new RegisterDeviceRequest("DEV-01", "Device 1", InstrumentType.Torque, ExplicitApiKey: key),
            "admin"
        );

        var verified = await service.VerifyApiKeyAsync("DEV-01", key);

        verified.Should().NotBeNull();
        verified!.DeviceId.Should().Be(reg.Device.DeviceId);
        verified.LastSeenAt.Should().NotBeNull();
        verified.LastSeenAt.Should().BeCloseTo(DateTime.UtcNow, TimeSpan.FromSeconds(5));
    }

    [Fact]
    public async Task VerifyApiKeyAsync_InvalidKey_ReturnsNull()
    {
        using var db = CreateInMemoryDbContext();
        var service = new DeviceService(db);

        await service.RegisterAsync(
            new RegisterDeviceRequest("DEV-02", "Device 2", InstrumentType.Torque, ExplicitApiKey: "correct_key"),
            "admin"
        );

        var verified = await service.VerifyApiKeyAsync("DEV-02", "wrong_key");

        verified.Should().BeNull();
    }

    [Fact]
    public async Task VerifyApiKeyAsync_InactiveDevice_ReturnsNull()
    {
        using var db = CreateInMemoryDbContext();
        var service = new DeviceService(db);

        const string key = "device_key";
        var reg = await service.RegisterAsync(
            new RegisterDeviceRequest("DEV-03", "Device 3", InstrumentType.Torque, ExplicitApiKey: key),
            "admin"
        );

        await service.SetActiveAsync(reg.Device.DeviceId, false);

        var verified = await service.VerifyApiKeyAsync("DEV-03", key);

        verified.Should().BeNull();
    }

    [Fact]
    public async Task UpdateHeartbeatAsync_UpdatesLastSeenAndFirmware()
    {
        using var db = CreateInMemoryDbContext();
        var service = new DeviceService(db);

        await service.RegisterAsync(
            new RegisterDeviceRequest("DEV-04", "Device 4", InstrumentType.Torque, FirmwareVersion: "1.0.0"),
            "admin"
        );

        await service.UpdateHeartbeatAsync("DEV-04", "1.1.0");

        var device = await service.GetByTransmitterIdAsync("DEV-04");
        device.Should().NotBeNull();
        device!.FirmwareVersion.Should().Be("1.1.0");
        device.LastSeenAt.Should().NotBeNull();
    }

    [Fact]
    public async Task ListAsync_FiltersByTypeAndActiveStatus()
    {
        using var db = CreateInMemoryDbContext();
        var service = new DeviceService(db);

        await service.RegisterAsync(new RegisterDeviceRequest("T1", "Torque Active", InstrumentType.Torque), "admin");
        var t2 = await service.RegisterAsync(new RegisterDeviceRequest("T2", "Torque Inactive", InstrumentType.Torque), "admin");
        await service.SetActiveAsync(t2.Device.DeviceId, false);

        await service.RegisterAsync(new RegisterDeviceRequest("V1", "Vernier Active", InstrumentType.Vernier), "admin");

        var allTorque = await service.ListAsync(instrumentType: InstrumentType.Torque);
        allTorque.Should().HaveCount(2);

        var activeTorque = await service.ListAsync(instrumentType: InstrumentType.Torque, activeOnly: true);
        activeTorque.Should().HaveCount(1);
        activeTorque[0].TransmitterId.Should().Be("T1");

        var allVernier = await service.ListAsync(instrumentType: InstrumentType.Vernier);
        allVernier.Should().HaveCount(1);
    }
}